// Drive the reader's width the way a user does, then read back the geometry.
const geometry = (page) =>
  page.evaluate(() => {
    const pane = document.querySelector('[data-testid="reader-pane"]');
    const slot = document.querySelector('[data-testid="reader-pane-slot"]');
    const rail = document.querySelector('[data-testid="project-panel"]');
    const canvas = document.querySelector('[data-testid="workflow-canvas"]');
    const nav = document.querySelector('[data-testid="reader-contents"]');
    const doc = document.querySelector('[data-testid="reader-body"] [data-density="reader"]');
    const r = (el) => (el ? el.getBoundingClientRect() : null);
    const box = (el) => {
      const rect = r(el);
      return rect ? { left: Math.round(rect.left), right: Math.round(rect.right), width: Math.round(rect.width) } : null;
    };
    return {
      mode: slot?.getAttribute("data-reader-mode") ?? null,
      pane: box(pane),
      slot: box(slot),
      rail: box(rail),
      canvas: box(canvas),
      nav: box(nav),
      navCollapsed: nav?.getAttribute("data-collapsed") ?? null,
      measure: box(doc),
      window: window.innerWidth,
    };
  });

// Drag the reader's edge until the pane reaches the requested width.
//
// One pass is not reliable: the drag listeners attach on mousedown, so the
// first synthetic moves of a gesture can land before React has committed. The
// assertions here are about the width the pane *settles* at (and how it clamps),
// not about pointer precision, so the helper corrects itself and gives up
// quietly once the width stops moving — which is exactly what a clamp looks
// like from the outside.
async function dragReaderTo(page, targetWidth) {
  let last = null;
  for (let attempt = 0; attempt < 5; attempt++) {
    const handle = await page.locator('[data-testid="reader-resize-handle"]').boundingBox();
    const pane = await page.locator('[data-testid="reader-pane"]').boundingBox();
    if (!handle || !pane) return;
    if (Math.abs(pane.width - targetWidth) <= 1) return;
    if (last !== null && Math.abs(pane.width - last) < 1) return; // clamped
    last = pane.width;

    const y = handle.y + handle.height / 2;
    const desiredLeft = pane.x + pane.width - targetWidth;
    await page.mouse.move(handle.x + handle.width / 2, y);
    await page.mouse.down();
    await page.waitForTimeout(80);
    await page.mouse.move(desiredLeft, y, { steps: 10 });
    await page.mouse.move(desiredLeft, y);
    await page.mouse.up();
    await page.waitForTimeout(300);
  }
}

